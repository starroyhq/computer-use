import ImageIO
import Vision

/// 运行时调用的辅助模式（--recognize-text、--paste-session）。它们在 NSApplication 启动之前运行，
/// 不显示界面、不取宿主锁，完成后直接退出。系统把它们的权限请求归到本 App 名下。
enum NativeHelperMode {
    /// 截图上限：Retina 整屏 PNG 一般不超过 20 MB。
    static let imageLimit = 64 << 20

    /// 从标准输入读一张 PNG 或 JPEG，输出 {"lines":[{"text","x","y","width","height"}]}，坐标是图片像素。
    /// 输入为空时识别一张内置的示例图：系统第一次为本 App 识别文字时要先在本机编译识别模型
    /// （实测约 1 分钟，之后几百毫秒），运行时启动后用它在后台提前完成这一步。
    static func recognizeText() -> Int32 {
        do {
            guard let data = try BoundedInput.readAll(from: .standardInput, limit: imageLimit) else { return 1 }
            let decoded = data.isEmpty ? warmUpImage() : CGImageSourceCreateWithData(data as CFData, nil).flatMap {
                CGImageSourceCreateImageAtIndex($0, 0, nil)
            }
            guard let image = decoded else { return 1 }
            let primary = try recognize(image, languages: ["en-US"])
            var lines = primary
            let supported = (try? VNRecognizeTextRequest().supportedRecognitionLanguages()) ?? []
            if let language = RecognitionLanguages.secondary(preferred: Locale.preferredLanguages, supported: supported) {
                lines = RecognizedLine.merge(primary: primary, secondary: try recognize(image, languages: [language, "en-US"]))
            }
            try FileHandle.standardOutput.write(contentsOf: RecognizedLine.encode(lines))
            return 0
        } catch {
            return 1
        }
    }

    /// 预热用的示例图：一行英文和一行中文，让两遍识别都加载各自的模型。
    private static func warmUpImage() -> CGImage? {
        let lines = ["Computer Use ls -la", "文字识别 Text"]
        guard let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 480, pixelsHigh: 120, bitsPerSample: 8,
                                            samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                                            bytesPerRow: 0, bitsPerPixel: 0),
              let context = NSGraphicsContext(bitmapImageRep: bitmap) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        defer { NSGraphicsContext.restoreGraphicsState() }
        NSGraphicsContext.current = context
        NSColor.white.setFill()
        NSRect(x: 0, y: 0, width: 480, height: 120).fill()
        let attributes: [NSAttributedString.Key: Any] = [.font: NSFont.systemFont(ofSize: 28), .foregroundColor: NSColor.black]
        for (index, line) in lines.enumerated() {
            NSAttributedString(string: line, attributes: attributes).draw(at: NSPoint(x: 16, y: 70 - 52 * index))
        }
        context.flushGraphics()
        return bitmap.cgImage
    }

    private static func recognize(_ image: CGImage, languages: [String]) throws -> [RecognizedLine] {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        // 不做语言校正：终端里的命令、路径和哈希不能被“纠正”成词典里的词。
        request.usesLanguageCorrection = false
        request.recognitionLanguages = languages
        try VNImageRequestHandler(cgImage: image, options: [:]).perform([request])
        return (request.results ?? []).compactMap { observation in
            guard let text = observation.topCandidates(1).first?.string, !text.isEmpty else { return nil }
            return RecognizedLine(text: text, normalized: observation.boundingBox, imageWidth: image.width, imageHeight: image.height)
        }
    }

    /// 一次粘贴的剪贴板会话，协议见 PasteSession。输入结束时（含出错退出）先换回剪贴板再退出。
    static func pasteSession() -> Int32 {
        let session = PasteSession(store: SystemPasteboard())
        defer { session.endOfInput() }
        var framer = LineFramer(maxBytes: 2 * PasteSession.textLimit)
        do {
            while true {
                let chunk = try HostEventReader.readChunk(from: .standardInput)
                if chunk.isEmpty { return 0 }
                for line in try framer.consume(chunk) {
                    guard var reply = session.handle(line) else { return 1 }
                    reply.append(10)
                    try FileHandle.standardOutput.write(contentsOf: reply)
                }
            }
        } catch {
            return 1
        }
    }
}

/// 系统通用剪贴板。只在 --paste-session 辅助进程里使用；读到的内容只用于换回，不会输出。
final class SystemPasteboard: PasteboardStore {
    /// 剪贴板管理工具的约定（nspasteboard.org）：内容是临时的、可能敏感、不是用户复制的，不要记录。
    static let markers = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"]
    private let board: NSPasteboard

    init(board: NSPasteboard = .general) { self.board = board }

    var changeCount: Int { board.changeCount }

    var readDenied: Bool {
        if #available(macOS 15.4, *) { return board.accessBehavior == .alwaysDeny }
        return false
    }

    func read() -> PasteboardRead {
        var items: [[PasteboardSnapshot.Entry]] = []
        var requested = 0, received = 0
        for item in board.pasteboardItems ?? [] {
            var entries: [PasteboardSnapshot.Entry] = []
            for type in item.types {
                requested += 1
                guard let data = item.data(forType: type) else { continue }
                received += 1
                entries.append(PasteboardSnapshot.Entry(type: type.rawValue, data: data))
            }
            items.append(entries)
        }
        if requested > 0 && received == 0 { return .denied }
        return .snapshot(PasteboardSnapshot(items: items), complete: received == requested)
    }

    func write(text: String) -> Int? {
        // 只留在本机，不同步到其他设备的通用剪贴板。
        board.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return nil }
        for marker in Self.markers { item.setData(Data(), forType: NSPasteboard.PasteboardType(marker)) }
        guard board.writeObjects([item]) else { return nil }
        return board.changeCount
    }

    func restore(_ snapshot: PasteboardSnapshot) -> Bool {
        board.clearContents()
        let items: [NSPasteboardItem] = snapshot.items.compactMap { entries in
            guard !entries.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type)) }
            return item
        }
        return items.isEmpty || board.writeObjects(items)
    }
}
